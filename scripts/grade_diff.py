"""List every grade that changed between two grades.jsonl files (e.g. after a grader fix).

    .venv\\Scripts\\python scripts\\grade_diff.py OLD NEW --why "..." --out results/quality/grade_changes.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def load(p: Path) -> dict[str, dict]:
    return {g["request_id"]: g for g in (json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip())}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("old", type=Path)
    ap.add_argument("new", type=Path)
    ap.add_argument("--why", required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    old, new = load(a.old), load(a.new)
    rows = []
    for rid, n in sorted(new.items()):
        o = old.get(rid)
        ol, nl = (o or {}).get("final_label"), n.get("final_label")
        oa, na = (o or {}).get("auto_label"), n.get("auto_label")
        if o is None or ol != nl or oa != na or bool(o.get("sure")) != bool(n.get("sure")):
            rows.append((n["qid"], n["setting"], n["drafter"].split("/")[-1], oa, na, ol, "sure" if (o or {}).get("sure") else "unsure",
                         nl, "sure" if n.get("sure") else "unsure", "yes" if n.get("override") else "",
                         "; ".join(n.get("reasons") or [])[:160]))
    L = ["# Grade changes", "", f"Generated by `scripts/grade_diff.py` from `{a.old.as_posix()}` -> `{a.new.as_posix()}`.",
         "", f"Why: {a.why}", "", f"{len(rows)} of {len(new)} grades changed (auto label, final label or sureness). An auto change under an author's override doesn't change the final label.", "",
         "| qid | setting | drafter | auto before | auto after | final before | | final after | | overridden | reasons now |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows):
        L.append("| " + " | ".join(str(x) for x in r).replace("\n", " ") + " |")
    a.out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
