"""How the library misleads a naive retriever: plain BM25 on the raw question, no model calls.

    .venv\\Scripts\\python scripts\\retriever_traps.py [--size 2400] [--top 5]
        ->  data/retrieval/traps.md, data/retrieval/traps.json

Traps = the questions with a `trap` in data/questions.jsonl, plus the unanswerable questions with
`distractors` (wrong numbers a reply could borrow). For each one:
  * the top hits at --size (rank, score, paper, citation, start of the text), with wrong-paper hits
    flagged;
  * where the right passage ranks (the first piece holding a gold evidence quote, as in
    eval_retrieval.py) at each piece size, or where the distractor ranks for an unanswerable one;
  * which of the question's terms the right passage shares (a vocabulary mismatch shares none).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from relay.retrieve import Retriever, tokenize  # noqa: E402
from scripts.eval_retrieval import fact_in, load_questions, quote_in  # noqa: E402

OUT_DIR = ROOT / "data" / "retrieval"
SIZES = (600, 1200, 2400)


def first_rank(full, pred):
    for h in full:
        if pred(h):
            return h
    return None


def analyse(q: dict, retrievers: dict, size: int, top: int) -> dict:
    out = {"qid": q["qid"], "paper": q["paper"], "trap": q.get("trap") or "distractors (unanswerable)",
           "question": q["question"], "ranks": {}}
    for s, r in retrievers.items():
        full = r.ranked(q["question"])
        if q["answerable"]:
            h = first_rank(full, lambda h: any(fact_in([h], f, r) for f in q["facts"]))
        else:
            evs = [ev for d in q.get("distractors", []) for ev in d["evidence"]]
            h = first_rank(full, lambda h: any(quote_in([h], ev, r) for ev in evs))
        wrong = first_rank(full, lambda h: h.piece.paper != q["paper"])
        out["ranks"][s] = {"right_or_distractor_rank": h.rank if h else None,
                           "its_cite": h.piece.cite() if h else None,
                           "first_wrong_paper_rank": wrong.rank if wrong else None,
                           "ranked_pieces": len(full)}
        if s == size:
            out["top_hits"] = [{"rank": x.rank, "score": round(x.score, 2), "paper": x.piece.paper,
                                "wrong_paper": x.piece.paper != q["paper"], "cite": x.piece.cite(),
                                "text": x.piece.text[:160].replace("\n", " ")} for x in full[:top]]
            qt = list(dict.fromkeys(tokenize(q["question"])))
            if h:
                pt = set(tokenize(h.piece.section + " " + h.piece.text))
                out["shared_terms"] = [t for t in qt if t in pt]
            elif q["answerable"]:
                # never scored: show the gold piece and what it shares with the question
                gold = next((p for p in r.pieces if any(ev["block_id"] in p.block_ids
                                                        for f in q["facts"] for ev in f["evidence"])), None)
                pt = set(tokenize(gold.section + " " + gold.text)) if gold else set()
                out["shared_terms"] = [t for t in qt if t in pt]
                out["gold_piece"] = gold.cite() if gold else None
            out["question_terms"] = qt
    return out


def render(rows: list[dict], size: int) -> str:
    L = ["# Retriever traps: plain BM25 on the raw question", "",
         f"Generated by `scripts/retriever_traps.py` (no model calls). Top hits at {size}-char pieces; "
         "ranks at every size. 'Right' = first piece holding a gold evidence quote; for unanswerable "
         "questions, the first piece holding a distractor (a wrong number a reply could borrow).", "",
         "| qid | trap | " + " | ".join(f"right/distractor rank @{s}" for s in SIZES) + " | first wrong-paper hit @"
         f"{size} | question terms shared with that piece |",
         "|---|---|" + "---|" * len(SIZES) + "---|---|"]
    for r in rows:
        ranks = [str(r["ranks"][s]["right_or_distractor_rank"] or "never (0 shared terms)") for s in SIZES]
        shared = r.get("shared_terms")
        L.append(f"| {r['qid']} | {r['trap']} | " + " | ".join(ranks) +
                 f" | {r['ranks'][size]['first_wrong_paper_rank']} | "
                 f"{len(shared)}/{len(r['question_terms'])}: {', '.join(shared) or '-'} |")
    for r in rows:
        L += ["", f"## {r['qid']} ({r['trap']})", "", f"> {r['question']}", ""]
        if r.get("gold_piece"):
            L.append(f"Right passage: {r['gold_piece']}, never scored: it shares none of the question's terms "
                     f"({', '.join(r['question_terms'])}).")
            L.append("")
        L += ["| rank | score | paper | citation | text |", "|---|---|---|---|---|"]
        for h in r["top_hits"]:
            flag = " **(wrong paper)**" if h["wrong_paper"] else ""
            L.append(f"| {h['rank']} | {h['score']} | {h['paper']}{flag} | {h['cite']} | "
                     f"{h['text'].replace('|', '/')} |")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=2400, choices=SIZES)
    ap.add_argument("--top", type=int, default=5)
    a = ap.parse_args()
    retrievers = {s: Retriever.from_blocks(s) for s in SIZES}
    qs = [q for q in load_questions() if q.get("trap") or (not q["answerable"] and q.get("distractors"))]
    rows = [analyse(q, retrievers, a.size, a.top) for q in qs]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "traps.json").write_text(json.dumps({"_generated_by": "scripts/retriever_traps.py", "size": a.size,
                                                    "rows": rows}, indent=1, ensure_ascii=False) + "\n",
                                        encoding="utf-8", newline="\n")
    md = render(rows, a.size)
    (OUT_DIR / "traps.md").write_text(md, encoding="utf-8", newline="\n")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
