"""Render the write-up: docs/WRITEUP.tmpl.md + docs/writeup/facts.json + results/tables.md -> docs/WRITEUP.md

    .venv\\Scripts\\python scripts\\render_writeup.py

Placeholders in the template:
  {{key}}          a fact's value from docs/writeup/facts.json (scripts/writeup_facts.py)
  {{quote:key}}    a fact's text as a block quote (verbatim, e.g. a reply from a saved run)
  {{table:Name}}   the section of results/tables.md whose heading starts with "## Name" (scripts/make_tables.py)
An unknown key or table stops the render. scripts/check_numbers.py checks that every number traces.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "docs" / "WRITEUP.tmpl.md"
FACTS = ROOT / "docs" / "writeup" / "facts.json"
TABLES = ROOT / "results" / "tables.md"
OUT = ROOT / "docs" / "WRITEUP.md"
PLACEHOLDER = re.compile(r"\{\{\s*(?:(table|quote):)?\s*([^{}]+?)\s*\}\}")
COMMENT = re.compile(r"<!--.*?-->", re.S)


class RenderError(Exception):
    pass


def fmt(v) -> str:
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def table_section(tables: str, name: str) -> str:
    """The body of the '## <name>...' section of tables.md, its heading as a bold caption."""
    lines = tables.splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith(f"## {name}:") or l == f"## {name}"), None)
    if start is None:
        raise RenderError(f"no section '## {name}' in results/tables.md")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    rows = [l for l in lines[start + 1:end] if l.startswith("|")]     # the table only; its method notes stay in tables.md
    if not rows:
        raise RenderError(f"section '## {name}' has no table")
    return f"**{lines[start][3:]}**\n\n" + "\n".join(rows)


def render(template: str, facts: dict, tables: str) -> str:
    def sub(m):
        kind, key = m.group(1), m.group(2)
        if kind == "table":
            return table_section(tables, key)
        if key not in facts:
            raise RenderError(f"unknown fact {key!r}")
        v = fmt(facts[key]["value"])
        if kind == "quote":
            return "\n".join("> " + line if line else ">" for line in v.splitlines())
        return v
    out = PLACEHOLDER.sub(sub, COMMENT.sub("", template))
    head = ("<!-- Generated by scripts/render_writeup.py from docs/WRITEUP.tmpl.md, docs/writeup/facts.json and "
            "results/tables.md. Do not edit: edit the template and re-render. -->\n")
    return head + re.sub(r"\n{3,}", "\n\n", out).strip() + "\n"


def load_inputs(template=TEMPLATE, facts=FACTS, tables=TABLES):
    return (template.read_text(encoding="utf-8"), json.loads(facts.read_text(encoding="utf-8")),
            tables.read_text(encoding="utf-8"))


def main() -> int:
    try:
        text = render(*load_inputs())
    except RenderError as e:
        print(f"render failed: {e}", file=sys.stderr)
        return 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
