"""The v2 resubmission's raw file and tables, from the saved real runs only. Nothing typed by hand.

    python scripts/build_results_v2.py   ->  submission_v2/results_v2.csv, submission_v2/tables_v2.md

results_v2.csv has one row per request of the v2 answer-quality runs on real Groq
(data/experiments/v2_quality/*.jsonl), with the brief's columns first. Columns these runs didn't record
are left empty and named in the header note of tables_v2.md: start_time (only the run's start is
known, in the request_id), retries, and the split of tokens into in/out (tokens_total is recorded).
Extra columns: drafter, pipeline, code_state, budget_wait_ms, claims_withheld, grade_sure, level.
The retrieval table comes from data/retrieval/v2.json (scripts/eval_retrieval_v2.py, no model calls).
"""
from __future__ import annotations

import csv
import json
import math
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "data" / "experiments" / "v2_quality"
OUT = ROOT / "submission_v2"

# file stem -> (pipeline, drafter, code state); see data/experiments/v2_quality/README.md
RUN_INFO = {
    "v2-20261113T110454Z": ("v2 claims", "openai/gpt-oss-120b", "first claims version (superseded)"),
    "v2-20261113T111518Z": ("v2 claims", "openai/gpt-oss-120b", "before quote-matching fixes (superseded)"),
    "v2@gpt-oss-20b-20261113T112718Z": ("v2 claims", "openai/gpt-oss-20b", "final"),
    "v2_prose@gpt-oss-20b-20261113T112718Z": ("v2 retrieval + prose", "openai/gpt-oss-20b", "final"),
}
COLS = ["request_id", "scenario", "source", "start_time", "first_token_ms", "total_ms", "status", "retries",
        "tokens_in", "tokens_out", "retrieval_setting", "answer_grade",
        "tokens_total", "budget_wait_ms", "claims_withheld", "grade_sure", "level", "pipeline", "drafter", "code_state"]
STATUS = {"answer": "ok", "refusal": "ok", "passages": "rate_limited", "busy": "error"}


def pct(xs, q):
    xs = sorted(xs)
    return xs[max(0, math.ceil(q * len(xs)) - 1)] if xs else None


def main() -> int:
    OUT.mkdir(exist_ok=True)
    rows = []
    for stem, (pipeline, drafter, state) in RUN_INFO.items():
        path = RUNS / f"{stem}.jsonl"
        for line in path.open(encoding="utf-8"):
            r = json.loads(line)
            rows.append({"request_id": f"{stem}-{r['qid']}", "scenario": "eval:v2_quality", "source": "real",
                         "start_time": "", "first_token_ms": r["first_token_ms"], "total_ms": r["total_ms"],
                         "status": STATUS.get(r["kind"], "error"), "retries": "", "tokens_in": "", "tokens_out": "",
                         "retrieval_setting": "hybrid small-to-big, BM25 top 3 kept, k=5" if state != "first claims version (superseded)"
                         else "hybrid small-to-big, k=3",
                         "answer_grade": r["grade"] or "", "tokens_total": r["tokens"],
                         "budget_wait_ms": r["budget_wait_ms"], "claims_withheld": r["dropped"],
                         "grade_sure": int(bool(r["sure"])), "level": r["level"], "pipeline": pipeline,
                         "drafter": drafter, "code_state": state})
    with (OUT / "results_v2.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        w.writerows(rows)

    L = ["# v2 tables", "", "Generated by `scripts/build_results_v2.py` from `results_v2.csv` (quality, real Groq) and "
         "`data/retrieval/v2.json` (retrieval, no model calls). Percentiles nearest-rank. Latency excludes the budget "
         "wait (the quality runs wait for budget on purpose). Not recorded by these runs, left empty in the CSV: "
         "start_time, retries, tokens split into in/out.", "",
         "## Answer quality, 18 graded questions, real Groq", "",
         "| pipeline | drafter | code state | n | correct and cited % | wrong % (incl. wrongly refused) | correctly refused % | "
         "unsure | tokens per answer | first verified sentence p50 / p95 (ms) | complete p50 / p95 (ms) | claims withheld |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    groups: dict[tuple, list] = {}
    for r in rows:
        groups.setdefault((r["pipeline"], r["drafter"], r["code_state"], r["request_id"].rsplit("-", 1)[0]), []).append(r)
    for (pipeline, drafter, state, _), rs in groups.items():
        n = len(rs)
        g = [r["answer_grade"] for r in rs]
        first = [r["first_token_ms"] - r["budget_wait_ms"] for r in rs]
        total = [r["total_ms"] - r["budget_wait_ms"] for r in rs]
        L.append(f"| {pipeline} | {drafter.split('/')[-1]} | {state} | {n} | {100 * g.count('correct') / n:.1f} | "
                 f"{100 * (g.count('wrong') + g.count('refused_wrongly')) / n:.1f} | {100 * g.count('refused_correctly') / n:.1f} | "
                 f"{sum(1 for r in rs if not r['grade_sure'])} | {statistics.mean(r['tokens_total'] for r in rs):.0f} | "
                 f"{pct(first, .5):.0f} / {pct(first, .95):.0f} | {pct(total, .5):.0f} / {pct(total, .95):.0f} | "
                 f"{sum(r['claims_withheld'] for r in rs)} |")
    L += ["", "Baselines from the original submission (results.csv there), same 18 questions: gpt-oss-120b 72.2% "
          "correct (auto-grades 66.7%), gpt-oss-20b 38.9% (auto-grades 44.4%). v2 grades are auto-grades only.", ""]

    ret = json.loads((ROOT / "data" / "retrieval" / "v2.json").read_text(encoding="utf-8"))
    L += ["## Retrieval, 46 answerable questions (14 original + 32 in plain wording), no model calls", "",
          "| variant | k | hit@k all | hit@k original | fact recall@k original | hit@k plain wording | context chars p50 | query ms p50 |",
          "|---|---|---|---|---|---|---|---|"]
    for x in ret:
        s = x["summary"]
        L.append(f"| {s['variant']} | {s.get('k', 3)} | {s['all_hit']:.0%} | {s['orig_hit']:.0%} | {s['orig_recall']:.0%} | "
                 f"{s['dev_hit']:.0%} | {s['ctx_p50']:.0f} | {s['ms_p50']:.0f} |")
    (OUT / "tables_v2.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
