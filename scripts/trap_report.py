"""Did the pipeline avoid each trap, and how? Facts only, from the graded raw answers.

    .venv\\Scripts\\python scripts\\trap_report.py [--raw-dir ...] [--grades ...] [--out results/quality/traps.md]

For Q5, Q12, Q13, Q14, Q17, every latest answer (each setting and drafter):
  * grade (final, after overrides) and whether the grader was sure;
  * the router's papers and rewritten query (or that the router was off / failed);
  * gold in sources: whether a source handed to the drafter holds a gold evidence block;
  * wrong-paper sources: how many sources came from another paper;
  * borrowed: a distractor number in the reply (unanswerable questions);
  * wrong-paper citations in the reply, and the reply's first 200 characters.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from relay.grade import load_questions  # noqa: E402
from scripts.build_results import read_answers  # noqa: E402

TRAPS = {"Q5": "ragged table row / same number in another row", "Q12": "borrow LibriSpeech WER",
         "Q13": "same term in the wrong paper", "Q14": "vocabulary mismatch", "Q17": "borrow Moshi's latency"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", type=Path, default=ROOT / "results" / "raw" / "answers")
    ap.add_argument("--grades", type=Path, default=ROOT / "results" / "quality" / "grades.jsonl")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "quality" / "traps.md")
    a = ap.parse_args(argv)
    qs = load_questions()
    with a.grades.open(encoding="utf-8") as f:
        grades = {g["request_id"]: g for g in (json.loads(x) for x in f if x.strip())}
    rows = [r for r in read_answers(a.raw_dir) if r["qid"] in TRAPS and not grades[r["request_id"]]["superseded"]]
    L = ["# Traps: did the pipeline avoid them?", "",
         "Generated by `scripts/trap_report.py` from the raw answers and `results/quality/grades.jsonl`. "
         "One row per answer (latest per setting and drafter). n is tiny: one question per trap.", ""]
    out = {}
    for qid, trap in TRAPS.items():
        q = qs[qid]
        gold_blocks = {ev["block_id"] for f in q.get("facts") or [] for ev in f["evidence"]}
        L += [f"## {qid}: {trap}", "", f"> {q['question']}", "",
              "| setting | drafter | grade | sure | router papers | router query | gold in sources | "
              "wrong-paper sources | borrowed | wrong-paper citations | reply (start) |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted((x for x in rows if x["qid"] == qid), key=lambda x: (x["setting"], x["drafter"])):
            g = grades[r["request_id"]]
            rep = r["reply"]
            ch = rep.get("checks") or {}
            router = ch.get("router")
            if router is None:
                rp, rq = "off", "-"
            elif "failed" in router:
                rp, rq = "failed", router["failed"][:60]
            else:
                rp, rq = ",".join(router.get("papers") or []) or "[]", (router.get("query") or "")[:110]
            srcs = rep.get("sources") or []
            if not srcs and ch.get("retrieval"):
                srcs = [{"pid": p, "paper": p.split(":")[0], "block_ids": []} for p in ch["retrieval"]["pids"]]
            gold_in = ("n/a" if not gold_blocks else
                       ("yes" if any(set(s.get("block_ids") or []) & gold_blocks for s in srcs) else
                        ("no" if rep.get("sources") else "not shown (refusal)")))
            wrong_src = sum(1 for s in srcs if s.get("paper") != q["paper"])
            text = (rep.get("text") or "").replace("\n", " ").replace("|", "/")[:200]
            L.append(f"| {r['setting']} | {r['drafter'].split('/')[-1]} | {g['final_label']} | "
                     f"{'yes' if g['sure'] or g['override'] else 'no'} | {rp} | {rq.replace('|', '/')} | {gold_in} | "
                     f"{wrong_src}/{len(srcs)} | {', '.join(g['borrowed']) or '-'} | "
                     f"{len(g['wrong_paper_citations'])} | {text} |")
            out.setdefault(qid, []).append({"setting": r["setting"], "drafter": r["drafter"], "label": g["final_label"],
                                            "router": router, "gold_in_sources": gold_in, "borrowed": g["borrowed"],
                                            "wrong_paper_sources": wrong_src})
        L.append("")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    a.out.with_suffix(".json").write_text(json.dumps({"_generated_by": "scripts/trap_report.py", "traps": out},
                                                     indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                                          newline="\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
